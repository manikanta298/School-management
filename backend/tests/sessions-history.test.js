import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import request from 'supertest';
process.env.NODE_ENV='test';process.env.JWT_SECRET='sessions-history-secret'.repeat(4);process.env.DATABASE_URL='postgres://test:test@localhost/test';process.env.FRONTEND_ORIGIN='http://localhost:5173';
const {pool}=await import('../src/config/db.js');const db=new PGlite();
await db.exec(await readFile(new URL('../database/schema.sql',import.meta.url),'utf8'));
const query=async(text,params)=>{const r=await db.query(text,params);return {...r,rowCount:r.rows.length||r.affectedRows||0};};pool.query=query;pool.connect=async()=>({query,release(){}});
const {app}=await import('../src/app.js');const {hashPassword}=await import('../src/services/auth.js');
const PW='SessionPassword!123',hash=await hashPassword(PW),origin='http://localhost:5173';
const insert=async(sql,p)=>(await query(sql,p)).rows[0].id;
const schoolA=(await query("SELECT id FROM schools WHERE slug='existing-school'")).rows[0].id;
const mk=async email=>{const id=await insert("INSERT INTO users(name,email,password_hash,role) VALUES($1,$2,$3,'admin') RETURNING id",[email,email,hash]);await query("INSERT INTO school_memberships(school_id,user_id,role,status,is_default) VALUES($1,$2,'admin','active',true)",[schoolA,id]);return id;};
const uid=await mk('one@example.com'),other=await mk('two@example.com');
after(async()=>{await db.close();await pool.end();});
const bearer=t=>({Authorization:`Bearer ${t}`});
const login=(email,pw=PW,ua='Phone')=>request(app).post('/api/auth/login').set('User-Agent',ua).send({email,password:pw});
test('login history records successes and failures per user',async()=>{
 await login('one@example.com','wrong-password-1!').then(r=>assert.equal(r.status,401));
 await login('nobody@example.com').then(r=>assert.equal(r.status,401));
 const ok=await login('one@example.com');assert.equal(ok.status,200);
 const r=await request(app).get('/api/auth/login-history').set(bearer(ok.body.accessToken));assert.equal(r.status,200);
 assert.deepEqual(r.body.items.map(e=>[e.success,e.reason]).sort(),[[false,'bad_password'],[true,null]]);
 const o=await login('two@example.com');const ro=await request(app).get('/api/auth/login-history').set(bearer(o.body.accessToken));assert.equal(ro.body.items.length,1);
 assert.ok(!JSON.stringify(r.body).includes('wrong-password'));
 assert.equal((await query("SELECT count(*)::int n FROM login_events WHERE user_id IS NULL AND success=false")).rows[0].n,1);
});
test('users list and revoke their own sessions; logout-all ends everything',async()=>{
 const a=await login('one@example.com','SessionPassword!123','Laptop'),b=await login('one@example.com','SessionPassword!123','Tablet');
 let r=await request(app).get('/api/auth/sessions').set(bearer(a.body.accessToken));assert.equal(r.status,200);
 const items=r.body.items;assert.ok(items.length>=3);assert.equal(items.filter(s=>s.current).length,1);assert.ok(items.some(s=>s.user_agent==='Tablet'));
 assert.ok(!('token_hash' in items[0]));
 const tablet=items.find(s=>s.user_agent==='Tablet');
 r=await request(app).delete(`/api/auth/sessions/${tablet.id}`).set('Origin',origin).set(bearer(a.body.accessToken));assert.equal(r.status,204);
 r=await request(app).get('/api/auth/me').set(bearer(b.body.accessToken));assert.equal(r.status,401);
 r=await request(app).delete(`/api/auth/sessions/${tablet.id}`).set('Origin',origin).set(bearer(a.body.accessToken));assert.equal(r.status,404);
 r=await request(app).delete('/api/auth/sessions/not-a-uuid').set('Origin',origin).set(bearer(a.body.accessToken));assert.equal(r.status,400);
 const o=await login('two@example.com');
 r=await request(app).delete(`/api/auth/sessions/${items.find(s=>s.current).id}`).set('Origin',origin).set(bearer(o.body.accessToken));assert.equal(r.status,404);
 r=await request(app).get('/api/auth/me').set(bearer(a.body.accessToken));assert.equal(r.status,200);
 r=await request(app).post('/api/auth/logout-all').set('Origin','https://evil.example').set(bearer(a.body.accessToken));assert.equal(r.status,403);
 r=await request(app).post('/api/auth/logout-all').set('Origin',origin).set(bearer(a.body.accessToken));assert.equal(r.status,204);
 r=await request(app).get('/api/auth/me').set(bearer(a.body.accessToken));assert.equal(r.status,401);
 r=await request(app).get('/api/auth/me').set(bearer(o.body.accessToken));assert.equal(r.status,200);
 r=await request(app).get('/api/auth/sessions');assert.equal(r.status,401);
});
