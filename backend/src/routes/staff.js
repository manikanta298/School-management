import { Router } from 'express';
import { authenticate,authorize } from '../middleware/auth.js';
import { validate } from '../validators/auth.js';
import * as v from '../validators/staff.js';
import * as model from '../models/staff.js';
import { fail } from '../services/auth.js';
export const staffRouter=Router();
staffRouter.use(authenticate,authorize('admin'),(_req,res,next)=>{res.set('Cache-Control','no-store');next();});
staffRouter.param('id',(_req,res,next,value)=>v.id.safeParse(value).success?next():res.status(400).json({message:'Invalid record ID'}));
const found=async(id)=>{const item=await model.find(id);if(!item)throw fail(404,'Record not found');return item;};
staffRouter.get('/',async(req,res)=>{const q=v.listQuery.safeParse(req.query);if(!q.success)return res.status(400).json({message:'Invalid query'});res.json({items:await model.list(q.data)});});
staffRouter.get('/:id',async(req,res)=>res.json({item:await found(req.params.id)}));
staffRouter.post('/',validate(v.staffBody),async(req,res)=>{const {id}=await model.save(null,req.body);res.status(201).json({item:await found(id)});});
staffRouter.put('/:id',validate(v.staffBody),async(req,res)=>{const saved=await model.save(req.params.id,req.body);if(!saved)throw fail(404,'Record not found');res.json({item:await found(saved.id)});});
staffRouter.delete('/:id',async(req,res)=>{if(!await model.remove(req.params.id))throw fail(404,'Record not found');res.status(204).end();});
staffRouter.use((err,_req,res,next)=>{
 if(err.code==='23505')return res.status(409).json({message:'Employee number already exists'});
 if(err.code==='23514')return res.status(400).json({message:'Invalid staff details. Check the joining date, phone, email and employee number.'});
 next(err);
});
