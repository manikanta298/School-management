import { Router } from 'express';
import { authenticate,authorize } from '../middleware/auth.js';
import { validate } from '../validators/auth.js';
import * as v from '../validators/fees.js';
import * as c from '../controllers/fees.js';
export const feesRouter=Router();
feesRouter.use(authenticate,authorize('admin','student','parent'),(_req,res,next)=>{res.set('Cache-Control','no-store');next();});
const admin=authorize('admin');
for(const key of ['id','paymentId'])feesRouter.param(key,(req,res,next,value)=>v.id.safeParse(value).success?next():res.status(400).json({message:'Invalid record ID'}));
const query=schema=>(req,res,next)=>{const result=schema.safeParse(req.query);if(!result.success)return res.status(400).json({message:'Invalid query'});req.feeQuery=result.data;next();};
feesRouter.get('/calendar',c.calendar);
feesRouter.get('/structures',admin,query(v.structureQuery),c.structures);
feesRouter.post('/structures',admin,validate(v.structure),c.saveStructure);
feesRouter.put('/structures/:id',admin,validate(v.structure),c.saveStructure);
feesRouter.get('/summary',query(v.summaryQuery),c.summary);
feesRouter.get('/invoices',query(v.listQuery),c.list);
feesRouter.post('/invoices',admin,validate(v.invoice),c.create);
feesRouter.get('/invoices/:id',c.find);
feesRouter.post('/invoices/:id/void',admin,validate(v.reason),c.voidInvoice);
feesRouter.get('/invoices/:id/payments',query(v.page),c.payments);
feesRouter.post('/invoices/:id/payments',admin,validate(v.payment),c.pay);
feesRouter.post('/invoices/:id/payments/:paymentId/reverse',admin,validate(v.reason),c.reverse);
feesRouter.get('/invoices/:id/events',admin,query(v.page),c.events);
feesRouter.use((err,_req,res,next)=>{
 if(err.code==='23505')return res.status(409).json({message:'Duplicate fee structure, invoice for this student/structure, or payment retry key'});
 if(['23503','23502'].includes(err.code))return res.status(409).json({message:'Missing reference or protected fee history'});
 if(err.code==='23514')return res.status(400).json({message:'Invalid fee amount/date, overpayment, void invoice, or protected financial history. Reverse active payments before voiding.'});
 if(['40001','40P01'].includes(err.code))return res.status(409).json({message:'Concurrent change. Reload and retry.'});next(err);
});
