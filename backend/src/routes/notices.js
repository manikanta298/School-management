import { Router } from 'express';
import { authenticate,authorize } from '../middleware/auth.js';
import { validate } from '../validators/auth.js';
import * as v from '../validators/notices.js';
import * as c from '../controllers/notices.js';
export const noticesRouter=Router();
noticesRouter.use(authenticate,(_req,res,next)=>{res.set('Cache-Control','no-store');next();});
const admin=authorize('admin');
const query=schema=>(req,res,next)=>{const parsed=schema.safeParse(req.query);if(!parsed.success)return res.status(400).json({message:'Invalid query'});req.noticeQuery=parsed.data;next();};
noticesRouter.param('id',(req,res,next,value)=>v.id.safeParse(value).success?next():res.status(400).json({message:'Invalid notice ID'}));
noticesRouter.get('/calendar',c.calendar);
noticesRouter.get('/manage',admin,query(v.manage),c.manage);
noticesRouter.get('/',query(v.list),c.list);
noticesRouter.post('/',admin,validate(v.create),c.save);
noticesRouter.get('/:id',c.find);
noticesRouter.put('/:id',admin,validate(v.update),c.save);
noticesRouter.post('/:id/publish',admin,validate(v.publish),c.transition('publish'));
for(const action of ['unpublish','archive','restore'])noticesRouter.post(`/:id/${action}`,admin,validate(v.action),c.transition(action));
noticesRouter.post('/:id/read',validate(v.acknowledge),c.acknowledge);
noticesRouter.get('/:id/readers',admin,query(v.readers),c.readers);
noticesRouter.get('/:id/audit',admin,query(v.page),c.audit);
noticesRouter.use((err,_req,res,next)=>{if(['23503','23502'].includes(err.code))return res.status(409).json({message:'Missing/mismatched audience reference or protected notice history'});if(err.code==='23514')return res.status(400).json({message:'Invalid notice dates, revision or state. Edit drafts only and choose expiry after availability; lifecycle actions need a reason.'});if(['40001','40P01'].includes(err.code))return res.status(409).json({message:'Concurrent notice change. Reload and retry.'});next(err);});
