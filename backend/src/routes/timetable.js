import { Router } from 'express';
import { authenticate,authorize } from '../middleware/auth.js';
import { validate } from '../validators/auth.js';
import * as v from '../validators/timetable.js';
import * as c from '../controllers/timetable.js';
export const timetableRouter=Router();
timetableRouter.use(authenticate,(_req,res,next)=>{res.set('Cache-Control','no-store');next();});
const admin=authorize('admin');
const query=schema=>(req,res,next)=>{const parsed=schema.safeParse(req.query);if(!parsed.success)return res.status(400).json({message:'Invalid query. Week start must be a real Monday date.'});req.scheduleQuery=parsed.data;next();};
timetableRouter.param('id',(req,res,next,value)=>v.id.safeParse(value).success?next():res.status(400).json({message:'Invalid record ID'}));
timetableRouter.get('/calendar',c.calendar);
timetableRouter.get('/assignments',admin,query(v.assignmentQuery),c.assignments);
timetableRouter.get('/rooms',admin,query(v.page),c.rooms);
timetableRouter.post('/rooms',admin,validate(v.roomCreate),c.saveRoom);
timetableRouter.put('/rooms/:id',admin,validate(v.roomUpdate),c.saveRoom);
timetableRouter.get('/slots',query(v.list),c.list);
timetableRouter.post('/slots',admin,validate(v.create),c.save);
timetableRouter.get('/slots/:id',c.find);
timetableRouter.put('/slots/:id',admin,validate(v.update),c.save);
timetableRouter.post('/slots/:id/deactivate',admin,validate(v.deactivate),c.deactivate);
timetableRouter.get('/slots/:id/audit',admin,query(v.page),c.audit);
timetableRouter.use((err,_req,res,next)=>{if(err.code==='23P01')return res.status(409).json({message:'Time conflict: section, teacher or room is booked for an overlapping occurrence.'});if(err.code==='23505')return res.status(409).json({message:'Room name already exists'});if(['23503','23502'].includes(err.code))return res.status(409).json({message:'Missing/mismatched reference or protected timetable history'});if(err.code==='23514')return res.status(400).json({message:'Invalid time/date, unavailable room/subject teacher, or protected schedule history. Check the year, weekday and teacher joining date.'});if(['40001','40P01'].includes(err.code))return res.status(409).json({message:'Concurrent schedule change. Reload and retry.'});next(err);});
