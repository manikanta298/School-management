import { Router } from 'express';
import { rateLimit } from 'express-rate-limit';
import * as c from '../controllers/auth.js';
import * as v from '../validators/auth.js';
import { authenticate,authorize,originGuard } from '../middleware/auth.js';
export const authRouter=Router(),usersRouter=Router();
const strict=rateLimit({windowMs:15*60*1000,limit:20,standardHeaders:'draft-8',legacyHeaders:false});
authRouter.use((_req,res,next)=>{res.set('Cache-Control','no-store');next();});
authRouter.post('/login',strict,v.validate(v.login),c.login);
authRouter.post('/refresh',strict,originGuard,c.refresh);
authRouter.post('/logout',originGuard,c.logout);
authRouter.get('/me',authenticate,(req,res)=>res.json({user:req.user}));
authRouter.param('userId',(_req,res,next,value)=>/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)?next():res.status(400).json({message:'Invalid user ID'}));
authRouter.post('/admin/users/:userId/revoke-sessions',authenticate,authorize('admin'),originGuard,c.adminRevokeSessions);
authRouter.get('/admin/users/:userId/login-history',authenticate,authorize('admin'),c.adminLoginHistory);
authRouter.get('/schools',authenticate,c.schools);
authRouter.post('/switch-school',strict,originGuard,authenticate,v.validate(v.switchSchool),c.switchSchool);
authRouter.param('id',(_req,res,next,value)=>/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)?next():res.status(400).json({message:'Invalid session ID'}));
authRouter.get('/sessions',authenticate,c.sessions);
authRouter.delete('/sessions/:id',authenticate,originGuard,c.revokeSession);
authRouter.post('/logout-all',authenticate,originGuard,c.logoutAll);
authRouter.get('/login-history',authenticate,c.loginHistory);
authRouter.post('/change-password',strict,authenticate,v.validate(v.changePassword),c.changePassword);
usersRouter.use(authenticate,authorize('admin'));
usersRouter.get('/',c.listUsers);
usersRouter.post('/',v.validate(v.createUser),c.createUser);
usersRouter.post('/:id/temporary-password',strict,c.temporaryPassword);
usersRouter.post('/:id/reset-password',strict,v.validate(v.resetPassword),c.resetPassword);
