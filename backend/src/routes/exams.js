import { Router } from 'express';
import { authenticate,authorize } from '../middleware/auth.js';
import { validate } from '../validators/auth.js';
import * as v from '../validators/exams.js';
import * as c from '../controllers/exams.js';
export const examsRouter=Router();
examsRouter.use(authenticate,(_req,res,next)=>{res.set('Cache-Control','no-store');next();});
const admin=authorize('admin'),staff=authorize('admin','teacher');
const query=schema=>(req,res,next)=>{const p=schema.safeParse(req.query);if(!p.success)return res.status(400).json({message:'Invalid query'});req.examQuery=p.data;next();};
for(const key of ['id','paperId','studentId'])examsRouter.param(key,(req,res,next,value)=>v.id.safeParse(value).success?next():res.status(400).json({message:'Invalid record ID'}));
examsRouter.get('/calendar',c.calendar);
examsRouter.get('/grading-scales',c.scales);
examsRouter.post('/grading-scales',admin,validate(v.scale),c.createScale);
examsRouter.get('/',query(v.list),c.list);
examsRouter.post('/',admin,validate(v.exam),c.create);
examsRouter.get('/:id',c.find);
examsRouter.get('/:id/papers',query(v.page),c.papers);
examsRouter.post('/:id/papers',admin,validate(v.paper),c.savePaper);
examsRouter.put('/:id/papers/:paperId',admin,validate(v.paper),c.savePaper);
examsRouter.delete('/:id/papers/:paperId',admin,c.removePaper);
examsRouter.get('/:id/candidates',staff,query(v.page),c.candidates);
examsRouter.post('/:id/candidates',admin,validate(v.candidate),c.addCandidate);
examsRouter.delete('/:id/candidates/:studentId',admin,c.removeCandidate);
examsRouter.get('/:id/papers/:paperId/marks',staff,query(v.page),c.register);
examsRouter.put('/:id/papers/:paperId/marks',staff,validate(v.marks),c.marks);
examsRouter.post('/:id/publish',admin,validate(v.publish),c.transition('publish'));
examsRouter.post('/:id/reopen',admin,validate(v.reason),c.transition('reopen'));
examsRouter.post('/:id/cancel',admin,validate(v.reason),c.transition('cancel'));
examsRouter.get('/:id/my-results',authorize('admin','student','parent'),query(v.page),c.results);
examsRouter.get('/:id/results',staff,query(v.page),c.results);
examsRouter.get('/:id/students/:studentId',authorize('admin','student','parent'),query(v.page),c.results);
examsRouter.get('/:id/audit',admin,query(v.page),c.audit);
examsRouter.use((err,_req,res,next)=>{if(err.code==='23505')return res.status(409).json({message:'Duplicate exam, paper, candidate or grading rule'});if(['23503','23502'].includes(err.code))return res.status(409).json({message:'Missing reference or protected exam history'});if(err.code==='23514')return res.status(400).json({message:'Invalid exam dates, score, state, grading rule or protected history. Complete all candidate/paper marks before publishing.'});if(['40001','40P01'].includes(err.code))return res.status(409).json({message:'Concurrent change. Reload and retry.'});next(err);});
