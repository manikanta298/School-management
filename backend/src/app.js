import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { env } from './config/env.js';
import { authRouter,usersRouter } from './routes/auth.js';
import { academicRouter } from './routes/academic.js';
import { studentsRouter,parentsRouter } from './routes/students.js';
import { teachersRouter } from './routes/teachers.js';
import { attendanceRouter } from './routes/attendance.js';
import { feesRouter } from './routes/fees.js';
import { examsRouter } from './routes/exams.js';
import { timetableRouter } from './routes/timetable.js';
import { noticesRouter } from './routes/notices.js';
import { dashboardRouter } from './routes/dashboard.js';
export const app=express();
app.set('trust proxy',env.TRUST_PROXY);app.disable('x-powered-by');
app.use(helmet());app.use(cors({origin:env.FRONTEND_ORIGIN,credentials:true}));
app.use(rateLimit({windowMs:60000,limit:120,standardHeaders:'draft-8',legacyHeaders:false}));
app.use('/api/exams',express.json({limit:'128kb'}));
app.use('/api/attendance',express.json({limit:'128kb'}));
app.use(express.json({limit:'16kb'}));app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.json({status:'ok'}));
app.use('/api/notices',noticesRouter);app.use('/api/dashboard',dashboardRouter);
app.use('/api/timetable',timetableRouter);
app.use('/api/exams',examsRouter);
app.use('/api/fees',feesRouter);
app.use('/api/attendance',attendanceRouter);
app.use('/api/teachers',teachersRouter);
app.use('/api/students',studentsRouter);app.use('/api/parents',parentsRouter);
app.use('/api/academic',academicRouter);
app.use('/api/auth',authRouter);app.use('/api/users',usersRouter);
app.use((_req,res)=>res.status(404).json({message:'Not found'}));
app.use((err,_req,res,_next)=>{
 if(err.code==='23505') return res.status(409).json({message:'Email already exists'});
 const status=err.status || 500;
 if(status>=500) console.error('Request failed:',err.code || err.name);
 res.status(status).json({message:status>=500?'Internal server error':err.type==='entity.parse.failed'?'Invalid JSON':err.message});
});
